import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { isMainModule, loadSystemModel, repositoryRoot } from "./lib/system-model.mjs";

export const taskRoutesPath = "_wiki/generated/task-routes.md";
export const ciImpactPath = ".github/generated/impact-rules.json";

function markdownCell(values) {
  return values.length ? values.map((value) => `\`${value}\``).join("<br>") : "None";
}

export function renderTaskRoutes(model) {
  const lines = [
    "# Generated Task Routes",
    "",
    "<!-- wiki:type = flow -->",
    "<!-- wiki:scope = bounder -->",
    "<!-- wiki:created = 2026-08-31 -->",
    "",
    "This page is compiled from the canonical system descriptor and carries no `wiki:updated` marker: its freshness is the descriptor's, enforced byte-for-byte by `npm run system:check`, not a hand-written date. Run `npm run system:generate` after changing impact rules. (`system/bounder-system.v1.json:1-1`)",
    "",
    "| Route | Changed paths | Components | Commands | Proof classes | Release-sensitive |",
    "|---|---|---|---|---|---|"
  ];
  for (const rule of model.impact_rules) {
    lines.push(`| \`${rule.id}\` | ${markdownCell(rule.paths)} | ${markdownCell(rule.components)} | ${markdownCell(rule.commands)} | ${markdownCell(rule.proof_classes)} | ${rule.release_sensitive ? "Yes" : "No"} |`);
  }
  lines.push(
    "",
    "## Use",
    "",
    "1. Run `npm run inspect` for current state.",
    "2. Run `npm run check:changed` for the least expensive sufficient plan.",
    "3. Run `npm run verify:changed` to execute the selected gates.",
    "4. Run `npm run verify` for an aggregate candidate.",
    "",
    "**Working if:** this page, CI selection, and local changed-path execution change together when one descriptor rule changes.",
    "",
    "## Provenance",
    "",
    "- Generated by `scripts/generate-system-views.mjs`.",
    "- Source: `system/bounder-system.v1.json:1-1`.",
    ""
  );
  return lines.join("\n");
}

export function renderCiImpact(model) {
  return `${JSON.stringify({
    version: "bounder-ci-impact/v1",
    source: "system/bounder-system.v1.json",
    descriptor_schema_version: model.schema_version,
    rules: model.impact_rules.map(({ id, paths, commands, release_sensitive }) => ({ id, paths, commands, release_sensitive }))
  }, null, 2)}\n`;
}

export async function generateSystemViews({ root = repositoryRoot, check = false } = {}) {
  const model = await loadSystemModel({ root, requirePaths: false });
  const outputs = new Map([
    [taskRoutesPath, renderTaskRoutes(model)],
    [ciImpactPath, renderCiImpact(model)]
  ]);
  const changed = [];
  for (const [path, expected] of outputs) {
    const absolute = join(root, path);
    let actual = null;
    try { actual = await readFile(absolute, "utf8"); } catch (error) { if (error?.code !== "ENOENT") throw error; }
    if (actual === expected) continue;
    changed.push(path);
    if (!check) await writeFile(absolute, expected, { encoding: "utf8" });
  }
  if (check && changed.length) throw new Error(`generated system views are stale: ${changed.join(", ")}`);
  return Object.freeze({ changed, paths: [...outputs.keys()] });
}

export async function runGenerateSystemViewsCli(args = process.argv.slice(2), logger = console) {
  if (args.some((argument) => argument !== "--check")) throw new Error("usage: npm run system:generate -- [--check]");
  const check = args.includes("--check");
  const result = await generateSystemViews({ check });
  logger.log(check ? `Generated system views current: ${result.paths.join(", ")}` : `Generated system views: ${result.paths.join(", ")}`);
  return result;
}

/* c8 ignore start -- direct-entry failure plumbing is covered through the exported command API. */
if (isMainModule(import.meta.url)) {
  runGenerateSystemViewsCli().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
